"""packc SKILL.md emitter: pack -> spec-compliant SKILL.md.

Frontmatter carries name + description (+ version/author). The body uses
progressive disclosure: overview -> per-skill detail -> flows -> escalation
policy -> pack metadata.
"""
from __future__ import annotations

from . import ast as A
from .parser import _MISSING


def _type_str(t) -> str:
    if isinstance(t, A.PrimType):
        return t.name
    if isinstance(t, A.EnumType):
        return "enum { " + ", ".join(t.members) + " }"
    if isinstance(t, A.ListType):
        return f"list[{_type_str(t.elem)}]"
    if isinstance(t, A.OptionalType):
        return f"{_type_str(t.inner)}?"
    if isinstance(t, A.RefType):
        return t.name
    return "?"


def _schema_table(schema: A.SchemaBlock) -> str:
    lines = ["| Field | Type | Required | Default |",
             "|---|---|---|---|"]
    for f in schema.fields:
        optional = isinstance(f.type, A.OptionalType)
        default = ""
        if f.has_default:
            v = f.default
            default = f"`{v[1]}`" if isinstance(v, tuple) and v[0] == "ident" else f"`{v!r}`"
        lines.append(f"| `{f.name}` | `{_type_str(f.type)}` | "
                     f"{'no' if optional else 'yes'} | {default} |")
    return "\n".join(lines)


def emit(pf: A.PackFile) -> str:
    p = pf.pack
    schemas = {s.name: s for s in pf.schemas}
    out: list[str] = []
    out.append("---")
    out.append(f"name: {p.name}")
    out.append(f"description: {p.description}")
    out.append(f"version: {p.version}")
    out.append(f"author: {p.author}")
    out.append("---")
    out.append("")
    out.append(f"# {p.name}")
    out.append("")
    out.append(f"> {p.description}")
    out.append("")
    out.append("## Overview")
    out.append("")
    out.append(f"This skill pack declares **{len(pf.skills)} skills**, "
               f"**{len(pf.schemas)} schemas**, **{len(pf.flows)} flows**, "
               f"and **{len(pf.escalate.rules) if pf.escalate else 0} escalation rules** "
               f"(packc v{p.version}, author {p.author}).")
    out.append("")
    out.append("Skills at a glance:")
    out.append("")
    for sk in pf.skills:
        out.append(f"- **{sk.name}** — {sk.description} (tool `{sk.tool}`)")
    out.append("")
    out.append("## Skills")
    out.append("")
    for sk in pf.skills:
        out.append(f"### {sk.name}")
        out.append("")
        out.append(f"{sk.description}")
        out.append("")
        out.append(f"- **Tool:** `{sk.tool}`")
        triggers = ", ".join(f'"{t}"' for t in sk.triggers or [])
        out.append(f"- **Triggers:** {triggers}")
        out.append("")
        if sk.input and sk.input in schemas:
            out.append(f"**Input schema** (`{sk.input}`):")
            out.append("")
            out.append(_schema_table(schemas[sk.input]))
            out.append("")
        if sk.output and sk.output in schemas:
            out.append(f"**Output schema** (`{sk.output}`):")
            out.append("")
            out.append(_schema_table(schemas[sk.output]))
            out.append("")
        out.append("**Steps:**")
        out.append("")
        for i, step in enumerate(sk.steps or [], 1):
            out.append(f"{i}. {step}")
        out.append("")
    if pf.flows:
        out.append("## Flows")
        out.append("")
        for fl in pf.flows:
            out.append(f"### {fl.name}")
            out.append("")
            out.append(f"Start at `{fl.start}`.")
            out.append("")
            for e in fl.edges:
                out.append(f"- on `{e.event}` → `{e.target}`")
            out.append("")
    if pf.escalate:
        esc = pf.escalate
        out.append("## Escalation policy")
        out.append("")
        out.append("| Rule | Condition | Tier |")
        out.append("|---|---|---|")
        for r in esc.rules:
            cond = "always" if r.condition is None else (
                f"`{r.condition.field} {r.condition.op} {r.condition.value!r}`")
            out.append(f"| `{r.name}` | {cond} | `{r.tier}` |")
        out.append("")
        if esc.defaults:
            out.append("### Default tiers")
            out.append("")
            out.append("| Action prefix | Tier |")
            out.append("|---|---|")
            for prefix, tier in esc.defaults:
                out.append(f"| `{prefix}` | `{tier}` |")
            out.append("")
        if esc.context:
            out.append(f"Rule conditions reference fields of the `{esc.context}` schema.")
            out.append("")
    out.append("## Pack metadata")
    out.append("")
    out.append(f"- Version: `{p.version}`")
    out.append(f"- Author: {p.author}")
    out.append(f"- Tools: {', '.join(f'`{t}`' for t in p.tools)}")
    out.append("")
    out.append(f"*Generated by packc from `{pf.filename}` — do not edit by hand; "
               f"edit the .pack source and re-emit.*")
    out.append("")
    return "\n".join(out)
