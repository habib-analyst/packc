"""packc conformance-test emitter: pack -> pytest file.

Generates golden-task tests per skill:
  * valid input  -> dispatch ok, output conforms to the output schema
  * invalid input (wrong type) -> ValidationError
  * unknown field -> ValidationError
  * unknown tool -> KeyError
plus registry tests (tools/list via the JSON-RPC layer, trigger coverage,
escalation-tier validity).

The generated file bakes in SERVER_PATH so `pytest <file>` runs standalone.
"""
from __future__ import annotations

from . import ast as A
from . import __version__ as _packc_version


def _sample_of(t, schemas: dict[str, A.SchemaBlock], depth: int = 0):
    if depth > 8:
        return None
    if isinstance(t, A.OptionalType):
        return _sample_of(t.inner, schemas, depth + 1)
    if isinstance(t, A.RefType):
        return _sample_of_schema(schemas[t.name], schemas, depth + 1)
    if isinstance(t, A.PrimType):
        return {"string": "sample", "int": 1, "float": 1.5, "bool": True}[t.name]
    if isinstance(t, A.EnumType):
        return t.members[0]
    if isinstance(t, A.ListType):
        return [_sample_of(t.elem, schemas, depth + 1)]
    raise TypeError(f"unknown type node {t!r}")


def _sample_of_schema(s: A.SchemaBlock, schemas: dict[str, A.SchemaBlock], depth: int = 0) -> dict:
    return {f.name: _sample_of(f.type, schemas, depth) for f in s.fields}


def _wrong_value_for(t, schemas: dict[str, A.SchemaBlock]):
    """A value guaranteed to fail validation for type t."""
    while isinstance(t, A.OptionalType):
        t = t.inner
    if isinstance(t, A.RefType):
        return "not-an-object"
    if isinstance(t, A.PrimType):
        return {"string": 12345, "int": "not-an-int", "float": "not-a-float",
                "bool": "not-a-bool"}[t.name]
    if isinstance(t, A.EnumType):
        return 12345
    if isinstance(t, A.ListType):
        return "not-a-list"
    return 12345


def _default_py(v):
    if isinstance(v, tuple) and v[0] == "ident":
        return v[1]
    return v


def _safe(name: str) -> str:
    return "".join(c if (c.isalnum() or c == "_") else "_" for c in name)


def emit(pf: A.PackFile, server_path: str) -> str:
    p = pf.pack
    schemas = {s.name: s for s in pf.schemas}
    L: list[str] = []
    L.append('"""Conformance tests for pack %r v%s.' % (p.name, p.version))
    L.append('')
    L.append('Generated by packc %s from %s. Run: pytest %s' % (_packc_version, pf.filename, __file__))
    L.append('"""')
    L.append("import importlib.util")
    L.append("import json")
    L.append("")
    L.append("import pytest")
    L.append("")
    L.append("SERVER_PATH = %r" % server_path)
    L.append("")
    L.append("")
    L.append("def _load_server():")
    L.append('    spec = importlib.util.spec_from_file_location("pack_server_under_test", SERVER_PATH)')
    L.append("    mod = importlib.util.module_from_spec(spec)")
    L.append("    spec.loader.exec_module(mod)")
    L.append("    return mod")
    L.append("")
    L.append("")
    L.append("srv = _load_server()")
    L.append("ValidationError = srv.ValidationError")
    L.append("")
    L.append("")
    L.append("EXPECTED_TOOLS = %r" % sorted(sk.tool for sk in pf.skills))
    L.append("")
    L.append("")
    L.append("def test_all_skills_registered_as_tools():")
    L.append("    assert sorted(srv.TOOLS) == EXPECTED_TOOLS")
    L.append("")
    L.append("")
    L.append("def test_tools_list_method():")
    L.append('    resp = srv.handle_request({"jsonrpc": "2.0", "id": 1,')
    L.append('                               "method": "tools/list", "params": {}})')
    L.append('    names = sorted(t["name"] for t in resp["result"]["tools"])')
    L.append("    assert names == EXPECTED_TOOLS")
    L.append("    for t in resp[\"result\"][\"tools\"]:")
    L.append('        assert t["inputSchema"]["type"] == "object"')
    L.append("")
    L.append("")
    L.append("def test_unknown_tool_rejected():")
    L.append('    with pytest.raises(KeyError):')
    L.append('        srv.dispatch("no_such_tool_in_pack", {})')
    L.append("")

    for sk in pf.skills:
        tool = sk.tool
        fn = _safe(tool)
        in_schema = schemas[sk.input]
        golden = _sample_of_schema(in_schema, schemas)
        # corrupt the first required field (fall back to first field)
        target = next((f for f in in_schema.fields
                       if not isinstance(f.type, A.OptionalType)), None)
        target = target or (in_schema.fields[0] if in_schema.fields else None)
        L.append("")
        L.append(f"def test_{fn}_valid_input_ok():")
        L.append(f"    args = {golden!r}")
        L.append(f"    result = srv.dispatch({tool!r}, args)")
        L.append('    assert result["ok"] is True')
        L.append(f'    assert result["tool"] == {tool!r}')
        if sk.output:
            L.append("    out_spec = srv.output_spec_for(%r)" % tool)
            L.append("    assert out_spec is not None")
            L.append('    srv.validate(result["output"], ("object", out_spec), "$output")')
        L.append("")
        L.append(f"def test_{fn}_invalid_input_rejected():")
        if target is None:
            L.append("    args = %r" % "not-a-dict")
            L.append("    with pytest.raises(ValidationError):")
            L.append(f"        srv.dispatch({tool!r}, args)")
        else:
            bad = dict(golden)
            inner = target.type
            while isinstance(inner, A.OptionalType):
                inner = inner.inner
            if isinstance(inner, A.RefType):
                # corrupt a nested field instead of the whole object
                sub = schemas[inner.name]
                sub_target = next((f for f in sub.fields
                                   if not isinstance(f.type, A.OptionalType)),
                                  sub.fields[0] if sub.fields else None)
                if sub_target is None:
                    bad[target.name] = "not-an-object"
                else:
                    sub_golden = _sample_of_schema(sub, schemas)
                    sub_golden[sub_target.name] = _wrong_value_for(sub_target.type, schemas)
                    bad[target.name] = sub_golden
            else:
                bad[target.name] = _wrong_value_for(target.type, schemas)
            L.append(f"    args = {bad!r}")
            L.append("    with pytest.raises(ValidationError):")
            L.append(f"        srv.dispatch({tool!r}, args)")
        L.append("")
        L.append(f"def test_{fn}_unknown_field_rejected():")
        L.append(f"    args = dict({golden!r})")
        L.append('    args["__packc_no_such_field__"] = 1')
        L.append("    with pytest.raises(ValidationError):")
        L.append(f"        srv.dispatch({tool!r}, args)")
        # defaults: dispatch with only strictly-required fields; the server
        # must fill declared defaults into validated_args
        strict_required = [f for f in in_schema.fields
                           if not isinstance(f.type, A.OptionalType) and not f.has_default]
        defaulted = [(f.name, _default_py(f.default)) for f in in_schema.fields if f.has_default]
        if defaulted:
            minimal = {f.name: _sample_of(f.type, schemas) for f in strict_required}
            L.append("")
            L.append(f"def test_{fn}_defaults_applied():")
            L.append(f"    args = {minimal!r}")
            L.append(f"    result = srv.dispatch({tool!r}, args)")
            L.append('    assert result["ok"] is True')
            for fname, dval in defaulted:
                L.append(f"    assert result['validated_args'][{fname!r}] == {dval!r}")

    L.append("")
    L.append("")
    L.append("def test_trigger_coverage():")
    L.append("    trigger_map = %r" % {sk.name: list(sk.triggers or []) for sk in pf.skills})
    L.append("    assert len(trigger_map) > 0")
    L.append("    for skill, triggers in trigger_map.items():")
    L.append("        assert len(triggers) >= 1, skill")
    L.append("        assert all(t.strip() for t in triggers), skill")
    if pf.escalate:
        tiers = sorted({r.tier for r in pf.escalate.rules}
                       | {t for _, t in pf.escalate.defaults})
        L.append("")
        L.append("")
        L.append("def test_escalation_tiers_valid():")
        L.append("    tiers = %r" % tiers)
        L.append('    assert set(tiers) <= {"auto", "confirm", "human_only"}')
        L.append("    assert len(tiers) > 0")
    L.append("")
    return "\n".join(L) + "\n"
