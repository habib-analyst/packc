"""packc MCP emitter: pack -> self-contained JSON-RPC 2.0 server over stdio.

Zero third-party dependencies. Each skill becomes a tool with a JSON Schema
inputSchema derived from the typed input schema. dispatch() validates
arguments (type errors rejected) and runs a typed contract shell that
returns a structured, documented result. Business logic is author-extensible
via a sibling `handlers` module (one function per tool name).
"""
from __future__ import annotations

import string as _string

from . import ast as A
from . import __version__ as _packc_version


# ------------------------------------------------------------------ specs ---

def _spec_of(t) -> tuple:
    if isinstance(t, A.PrimType):
        return (t.name,)
    if isinstance(t, A.EnumType):
        return ("enum", list(t.members))
    if isinstance(t, A.ListType):
        return ("list", _spec_of(t.elem))
    if isinstance(t, A.OptionalType):
        return ("optional", _spec_of(t.inner))
    if isinstance(t, A.RefType):
        return ("ref", t.name)
    raise TypeError(f"unknown type node {t!r}")


def _jsonschema_of(t, schemas: dict[str, A.SchemaBlock], _seen: frozenset = frozenset()) -> dict:
    if isinstance(t, A.PrimType):
        return {"string": {"type": "string"}, "int": {"type": "integer"},
                "float": {"type": "number"}, "bool": {"type": "boolean"}}[t.name]
    if isinstance(t, A.EnumType):
        return {"type": "string", "enum": list(t.members)}
    if isinstance(t, A.ListType):
        return {"type": "array", "items": _jsonschema_of(t.elem, schemas, _seen)}
    if isinstance(t, A.OptionalType):
        return _jsonschema_of(t.inner, schemas, _seen)
    if isinstance(t, A.RefType):
        if t.name in _seen:
            raise ValueError(f"cycle while inlining schema {t.name}")
        return _object_jsonschema(schemas[t.name], schemas, _seen | {t.name})
    raise TypeError(f"unknown type node {t!r}")


def _default_json(v):
    if isinstance(v, tuple) and v[0] == "ident":
        return v[1]
    return v


def _object_jsonschema(s: A.SchemaBlock, schemas: dict[str, A.SchemaBlock],
                       _seen: frozenset = frozenset()) -> dict:
    props, required = {}, []
    for f in s.fields:
        js = _jsonschema_of(f.type, schemas, _seen)
        if f.has_default:
            js = dict(js)
            js["default"] = _default_json(f.default)
        props[f.name] = js
        if not isinstance(f.type, A.OptionalType) and not f.has_default:
            required.append(f.name)
    return {"type": "object", "properties": props, "required": required,
            "additionalProperties": False}


def _object_spec(s: A.SchemaBlock) -> dict:
    return {f.name: {"spec": _spec_of(f.type),
                     "required": not isinstance(f.type, A.OptionalType) and not f.has_default,
                     "default": _default_json(f.default) if f.has_default else None}
            for f in s.fields}


# --------------------------------------------------------------- template ---

_SERVER_TEMPLATE = _string.Template(r'''#!/usr/bin/env python3
"""$PACK_NAME v$PACK_VERSION — MCP-style tool server (JSON-RPC 2.0 over stdio).

$PACK_DESCRIPTION

Generated by packc $PACKC_VERSION from $SOURCE.
Zero third-party dependencies. Each skill in the pack is exposed as a tool
with a JSON Schema inputSchema derived from the pack's typed schemas.

Typed contract shells: dispatch() validates arguments against the declared
input schema (type errors are rejected) and returns a structured result. The
business logic is author-extensible: create a `handlers` module next to this
file exposing one function per tool name, e.g.:

    # handlers.py
    def $FIRST_TOOL(args):
        return {"rooms": [...]}   # must be JSON-serializable

When present, the author's function runs instead of the contract shell.
"""
import json
import sys

PACK_NAME = $PACK_NAME_R
PACK_VERSION = $PACK_VERSION_R
PACK_DESCRIPTION = $PACK_DESCRIPTION_R

# name -> {field: {"spec": <type spec>, "required": bool}}
SCHEMAS = $SCHEMAS_R

# tool name -> tool record
TOOLS = $TOOLS_R


class ValidationError(Exception):
    """Raised when arguments fail schema validation."""

    def __init__(self, message, path="$$", code="TYPE_MISMATCH"):
        super().__init__(message)
        self.message = message
        self.path = path
        self.code = code


def _resolve(spec):
    while spec[0] == "ref":
        spec = ("object", SCHEMAS[spec[1]])
    return spec


def validate(value, spec, path="$$"):
    """Recursively validate `value` against a type spec. Returns the
    validated value; raises ValidationError on any mismatch."""
    kind = spec[0]
    if kind == "optional":
        if value is None:
            return None
        return validate(value, spec[1], path)
    if kind == "ref":
        return validate(value, _resolve(spec), path)
    if kind == "object":
        if not isinstance(value, dict):
            raise ValidationError(
                "expected object, got %s" % type(value).__name__, path, "TYPE_MISMATCH")
        fields = spec[1]
        out = {}
        for fname, finfo in fields.items():
            if fname not in value:
                if finfo["required"]:
                    raise ValidationError("missing required field %r" % fname,
                                          path, "MISSING_FIELD")
                if finfo["default"] is not None:
                    out[fname] = finfo["default"]
                continue
            out[fname] = validate(value[fname], finfo["spec"], path + "." + fname)
        for k in value:
            if k not in fields:
                raise ValidationError("unknown field %r" % k, path, "UNKNOWN_FIELD")
        return out
    if kind == "string":
        if not isinstance(value, str) or isinstance(value, bool):
            raise ValidationError("expected string, got %r" % (value,), path, "TYPE_MISMATCH")
        return value
    if kind == "int":
        if not isinstance(value, int) or isinstance(value, bool):
            raise ValidationError("expected int, got %r" % (value,), path, "TYPE_MISMATCH")
        return value
    if kind == "float":
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValidationError("expected float, got %r" % (value,), path, "TYPE_MISMATCH")
        return value
    if kind == "bool":
        if not isinstance(value, bool):
            raise ValidationError("expected bool, got %r" % (value,), path, "TYPE_MISMATCH")
        return value
    if kind == "enum":
        if not isinstance(value, str) or value not in spec[1]:
            raise ValidationError("expected one of %r, got %r" % (spec[1], value),
                                  path, "ENUM_MISMATCH")
        return value
    if kind == "list":
        if not isinstance(value, list):
            raise ValidationError("expected list, got %r" % (value,), path, "TYPE_MISMATCH")
        return [validate(v, spec[1], "%s[%d]" % (path, i)) for i, v in enumerate(value)]
    raise ValidationError("unknown spec kind %r" % (kind,), path, "INTERNAL")


def sample(spec, _depth=0):
    """Build a golden sample value conforming to a type spec."""
    if _depth > 8:
        return None
    kind = spec[0]
    if kind == "optional":
        return sample(spec[1], _depth + 1)
    if kind == "ref":
        return sample(_resolve(spec), _depth + 1)
    if kind == "object":
        return {fname: sample(finfo["spec"], _depth + 1)
                for fname, finfo in spec[1].items()}
    if kind == "string":
        return "sample"
    if kind == "int":
        return 1
    if kind == "float":
        return 1.5
    if kind == "bool":
        return True
    if kind == "enum":
        return spec[1][0]
    if kind == "list":
        return [sample(spec[1], _depth + 1)]
    raise ValueError("unknown spec kind %r" % (kind,))


def _contract_shell(tool_name, validated):
    out_spec = TOOLS[tool_name]["output_spec"]
    return {
        "ok": True,
        "pack": PACK_NAME,
        "tool": tool_name,
        "validated_args": validated,
        "output": sample(("object", out_spec)) if out_spec else None,
        "contract": "shell",
        "note": ("packc typed contract shell: arguments validated against the declared "
                 "schema; no author handler registered. Create a 'handlers' module next to "
                 "this file with a function named %r to implement business logic."
                 % tool_name),
    }


try:
    import handlers as _author_handlers
except Exception:  # pragma: no cover - optional extension point
    _author_handlers = None


def _run_handler(tool_name, validated):
    if _author_handlers is not None:
        fn = getattr(_author_handlers, tool_name, None)
        if callable(fn):
            return {"ok": True, "pack": PACK_NAME, "tool": tool_name,
                    "output": fn(validated), "contract": "author"}
    return _contract_shell(tool_name, validated)


def dispatch(tool_name, args):
    """Validate args against the tool's input schema and run it.

    Raises KeyError for unknown tools and ValidationError for bad args.
    """
    if tool_name not in TOOLS:
        raise KeyError("unknown tool %r; known tools: %s" % (tool_name, sorted(TOOLS)))
    if not isinstance(args, dict):
        raise ValidationError("tool arguments must be an object", "$$", "TYPE_MISMATCH")
    validated = validate(args, ("object", TOOLS[tool_name]["input_spec"]), "$$")
    return _run_handler(tool_name, validated)


def output_spec_for(tool_name):
    """Return the tool's output type spec (or None)."""
    return TOOLS[tool_name]["output_spec"]


# ------------------------------------------------- JSON-RPC 2.0 / stdio ---

def _ok(req_id, result):
    return {"jsonrpc": "2.0", "id": req_id, "result": result}


def _err(req_id, code, message):
    return {"jsonrpc": "2.0", "id": req_id, "error": {"code": code, "message": message}}


def handle_request(req):
    rid = req.get("id") if isinstance(req, dict) else None
    if not isinstance(req, dict) or req.get("jsonrpc") != "2.0":
        return _err(rid, -32600, "invalid JSON-RPC 2.0 request")
    method = req.get("method")
    params = req.get("params") or {}
    if method == "initialize":
        return _ok(rid, {"protocol": "packc-mcp/1.0", "pack": PACK_NAME,
                         "version": PACK_VERSION, "tools": sorted(TOOLS)})
    if method == "tools/list":
        return _ok(rid, {"tools": [
            {"name": n, "description": t["description"], "inputSchema": t["input_schema"]}
            for n, t in sorted(TOOLS.items())]})
    if method == "tools/call":
        name = params.get("name")
        args = params.get("arguments", {})
        try:
            result = dispatch(name, args)
        except KeyError as e:
            return _err(rid, -32602, str(e))
        except ValidationError as e:
            return _err(rid, -32602,
                         "argument validation failed at %s: %s" % (e.path, e.message))
        return _ok(rid, {"content": [{"type": "text", "text": json.dumps(result)}]})
    return _err(rid, -32601, "unknown method %r" % (method,))


def serve():
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
        except json.JSONDecodeError as e:
            sys.stdout.write(json.dumps(_err(None, -32700, "parse error: %s" % e)) + "\n")
            sys.stdout.flush()
            continue
        sys.stdout.write(json.dumps(handle_request(req)) + "\n")
        sys.stdout.flush()


if __name__ == "__main__":
    serve()
''')


def emit(pf: A.PackFile) -> str:
    p = pf.pack
    schemas = {s.name: s for s in pf.schemas}
    schemas_r = {name: _object_spec(s) for name, s in schemas.items()}
    tools: dict[str, dict] = {}
    for sk in pf.skills:
        in_schema = schemas[sk.input]
        out_schema = schemas[sk.output] if sk.output else None
        tools[sk.tool] = {
            "skill": sk.name,
            "description": sk.description,
            "input_schema": _object_jsonschema(in_schema, schemas),
            "output_schema": _object_jsonschema(out_schema, schemas) if out_schema else None,
            "input_spec": _object_spec(in_schema),
            "output_spec": _object_spec(out_schema) if out_schema else None,
            "steps": list(sk.steps or []),
            "triggers": list(sk.triggers or []),
        }
    first_tool = next(iter(tools)) if tools else "example_tool"
    return _SERVER_TEMPLATE.substitute(
        PACK_NAME=p.name,
        PACK_VERSION=p.version,
        PACK_DESCRIPTION=(p.description or "").replace("\n", " "),
        PACKC_VERSION=_packc_version,
        SOURCE=pf.filename,
        FIRST_TOOL=first_tool,
        PACK_NAME_R=repr(p.name),
        PACK_VERSION_R=repr(p.version),
        PACK_DESCRIPTION_R=repr(p.description or ""),
        SCHEMAS_R=repr(schemas_r),
        TOOLS_R=repr(tools),
    )
